i18n.use(initReactI18next).init({
  resources,
  lng: typeof window !== "undefined" ? localStorage.getItem("smart-ops-lang") || "en" : "en",
  fallbackLng: "en",
  interpolation: { escapeValue: false },
});

function applyLocale(lng: string) {
  if (typeof document !== "undefined") {
    document.documentElement.dir = lng === "ar" ? "rtl" : "ltr";
    document.documentElement.lang = lng;
    document.documentElement.style.fontFamily =
      lng === "ar" ? "'Tajawal', 'Segoe UI', sans-serif" : "'Inter', 'Segoe UI', sans-serif";
    localStorage.setItem("smart-ops-lang", lng);
  }
}

i18n.on("languageChanged", applyLocale);
applyLocale(i18n.language);

export default i18n;
