export function buildMainNavConfig(t: (k: string) => string, opts: {
  isBranchSupervisor: boolean;
  showAdminHub: boolean;
  isOwner: boolean;
  isSuperAdmin?: boolean;
  isExternalAccountant?: boolean;
  isGeneralManager?: boolean;
}): NavConfig[] {
  const {
    isBranchSupervisor,
    showAdminHub,
    isOwner,
    isSuperAdmin = false,
    isExternalAccountant = false,
  } = opts;

  const opsItemsFull = [
    { to: "/", label: t("dashboard"), icon: icons.dashboard, primary: !isBranchSupervisor },
    { to: "/dashboard/heartbeat", label: t("cafeHeartbeat"), icon: icons.heartbeat },
    { to: "/forecast", label: t("forecast"), icon: icons.forecast },
    { to: "/prep-list", label: t("opsPrepList"), icon: icons.prepList, primary: isBranchSupervisor },
    { to: "/shift-closing", label: t("shiftClosing"), icon: icons.shiftClosing },
  ];
  const opsItemsBranchOnly = [
    { to: "/", label: t("dashboard"), icon: icons.dashboard },
    { to: "/prep-list", label: t("opsPrepList"), icon: icons.prepList, primary: true },
    { to: "/shift-closing", label: t("shiftClosing"), icon: icons.shiftClosing },
    { to: "/waste-tracker", label: t("wasteEntry"), icon: icons.waste },
  ];

  const dataItems = [
    { to: "/upload-center", label: t("uploadCenter"), icon: icons.upload },
    { to: "/ingredients", label: t("recipeInventory"), icon: icons.ingredients },
    { to: "/finance", label: t("financialHub") ?? "Finance Hub", icon: icons.financial },
    { to: "/waste-tracker", label: t("wasteEntry"), icon: icons.waste },
    { to: "/reconciliation", label: t("reconciliation"), icon: icons.reconciliation },
  ].filter(
    (i) =>
      !(isExternalAccountant && ["/upload-center", "/ingredients"].includes(i.to)) &&
      !(isBranchSupervisor && ["/upload-center", "/ingredients", "/finance", "/reconciliation"].includes(i.to))
  );

  const adminItems = [{ to: "/admin-hub", label: t("adminDashboard"), icon: icons.admin }];

  return [
    {
      items: isBranchSupervisor ? opsItemsBranchOnly : opsItemsFull,
      show: true,
    },
    {
      items: dataItems,
      show: dataItems.length > 0,
    },
    {
      items: adminItems,
      show: showAdminHub || isOwner,
    },
  ].filter((c) => c.show !== false);
}
